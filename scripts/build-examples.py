"""Rebuild examples/ from the real recorded sessions in tests/fixtures.

Run from the repository root: python scripts/build-examples.py

Each example replays two real recordings, one per agent, through the real
`hook` code into a throwaway project, keeps the resulting ledger with paths
replaced by a neutral project path, and compiles it. It also writes what the
README shows: the save when the first agent stopped (before/SAVE.md), the
block the second agent was given at its SessionStart (context.txt), and the
generated part of README.md. Inspect git diff before committing.

interrupted-by-limit has no real rate-limit recording behind it: Claude Code
has not been recorded hitting one yet. It uses the real StopFailure payload
(error "authentication_failed") with the error field changed to "rate_limit",
the value Claude Code documents for a rate limit. Its README says so.
"""
