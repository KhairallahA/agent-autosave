ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agent_autosave import background, capture, timeouts  # noqa: E402
from agent_autosave.installer.install import install  # noqa: E402

FIXTURES = ROOT / "tests/fixtures"
CLAUDE = FIXTURES / "claude-code/sessions/lifecycle"
CODEX = FIXTURES / "codex/sessions/plan-handoff"
CODEX_ROLLOUT = FIXTURES / "codex/rollouts/rollout-real-session.jsonl"
CODEX_CWD = "/private/tmp/aa-codex"
PROJECT = "~/projects/hello"  # what every real path becomes
TRANSCRIPTS = {"claude-code": "~/.claude/projects/-projects-hello/{}.jsonl",
               "codex": "~/.codex/sessions/2026/10/15/rollout-{}.jsonl"}
STOP_FAILURE = FIXTURES / "claude-code/payloads/StopFailure.json"
README_START = "<!-- generated by scripts/build-examples.py: do not edit below -->"


def rate_limited(rows: list[dict]) -> list[dict]:
    """The work session cut off by a rate limit: its last Stop becomes a
    StopFailure (the real payload, error set to "rate_limit"), and the
    /compact and restart that followed it are dropped before the SessionEnd."""
    last_stop = max(i for i, r in enumerate(rows) if r["payload"]["hook_event_name"] == "Stop")
    stop = rows[last_stop]["payload"]
    failure = json.loads(STOP_FAILURE.read_text(encoding="utf-8"))
    payload = dict(failure["payload"], error="rate_limit", session_id=stop["session_id"], cwd=stop["cwd"],
                   transcript_path=stop["transcript_path"],
                   last_assistant_message="You've hit your usage limit. Your limit resets at 4am.")
    payload.pop("prompt_id", None)
    cut = dict(rows[last_stop], payload=payload)
    end = [r for r in rows[last_stop + 1:] if r["payload"]["hook_event_name"] == "SessionEnd"][-1:]
    return rows[:last_stop] + [cut] + end


HANDOFF_NOTE = ("Step 1 is done: hello.py prints hello autosave. Next: run python3 hello.py, then the failing "
                "check python3 -c \"raise SystemExit(7)\". Nothing risky in flight.")


def low_battery(rows: list[dict]) -> list[dict]:
    """Codex near its 5-hour limit: its rollout reports 91% used (a
    token_count row in the shape codex-rs writes), so the next prompt asks
    it for a handoff note, and Codex records one with `note --type handoff`.
    The recorded session has no such row or note; both are added here."""
    rows = [dict(r) for r in rows]
    rows[0]["_usage"] = 91.0
    second = [i for i, r in enumerate(rows) if r["payload"]["hook_event_name"] == "UserPromptSubmit"][1]
    rows[second]["_then"] = ["note", HANDOFF_NOTE, "--type", "handoff"]
    rows[second]["_ask"] = True
    return rows


def near_limit(rows: list[dict]) -> list[dict]:
    """Claude Code near its 5-hour limit: before the second prompt its status
    line reports 88% used (the payload fields Claude Code documents for
    statusLine commands), so that prompt asks for a handoff note and Claude
    records one. Neither the reading nor the note is in the recording."""
    rows = [dict(r) for r in rows]
    second = [i for i, r in enumerate(rows) if r["payload"]["hook_event_name"] == "UserPromptSubmit"][1]
    rows[second].update(_statusline=88.0, _ask=True, _then=["note", HANDOFF_NOTE, "--type", "handoff"])
    return rows


# The 5-hour window the near-limit reading reports: it resets at 04:00 UTC.
RESETS_AT = int(datetime(2026, 10, 15, 4, 0, tzinfo=timezone.utc).timestamp())
GO_EXAMPLES = {"one-key-switch"}  # their replay also writes go.txt


def statusline_reading(project: Path, data: dict, percent: float) -> None:
    """What Claude Code's status line command does with one payload: the
    line is not kept, the usage reading is recorded."""
    from agent_autosave import statusline
    payload = {"session_id": data["session_id"], "cwd": str(project), "context_window": {"used_percentage": 63},
               "rate_limits": {"five_hour": {"used_percentage": percent, "resets_at": RESETS_AT}}}
    statusline.render(json.dumps(payload).encode())


# (agent, recording, session id prefix[, edit]): the work session, then the pick-up session.
EXAMPLES = {
    "claude-to-codex": (("claude-code", CLAUDE, "5145dfc5"), ("codex", CODEX, "01a13fd6")),
    "codex-to-claude": (("codex", CODEX, "01a13fcf-cfdf"), ("claude-code", CLAUDE, "5e43db48")),
    "interrupted-by-limit": (("claude-code", CLAUDE, "5145dfc5", rate_limited), ("codex", CODEX, "01a13fd6")),
    "low-battery-handoff": (("codex", CODEX, "01a13fcf-cfdf", low_battery), ("claude-code", CLAUDE, "5e43db48")),
    "one-key-switch": (("claude-code", CLAUDE, "5145dfc5", near_limit, rate_limited), ("codex", CODEX, "01a13fd6")),
}


def recordings(folder: Path) -> list[dict]:
    rows = [json.loads(p.read_text(encoding="utf-8")) for p in folder.glob("*.json")]
    return sorted(rows, key=lambda r: r["recorded_at"])


def session(folder: Path, session_id: str) -> list[dict]:
    """One recorded session, through its last SessionEnd."""
    rows = [r for r in recordings(folder) if r["payload"]["session_id"].startswith(session_id)]
    last = max(i for i, r in enumerate(rows) if r["payload"]["hook_event_name"] == "SessionEnd")
    return rows[:last + 1]


def localize(agent: str, row: dict, project: Path, rollout: Path) -> dict:
    """Point a recorded payload at the scratch project."""
    if agent == "codex":
        data = json.loads(json.dumps(row["payload"]).replace(CODEX_CWD, str(project)))
        data["transcript_path"] = str(rollout)
        return data
    data = json.loads(json.dumps(row["payload"]))
    data["cwd"] = str(project)
    inputs = data.get("tool_input")
    if isinstance(inputs, dict) and "file_path" in inputs:
        inputs["file_path"] = str(project / Path(inputs["file_path"]).name)
    return data


def codex_rollout(path: Path, rows: list[dict]) -> Path:
    """Real Codex CommandExecution rows carrying each recorded command's exit code."""
    template = next(json.loads(line) for line in CODEX_ROLLOUT.read_text(encoding="utf-8").splitlines()
                    if '"CommandExecution"' in line and '"exit_code"' in line)
    lines = []
    for r in rows:
        p = r["payload"]
        if p.get("tool_name") == "Bash":
            row = json.loads(json.dumps(template))
            row["payload"]["item"].update(id=p["tool_use_id"],
                                          exit_code=7 if "SystemExit(7)" in p["tool_input"]["command"] else 0)
            lines.append(json.dumps(row))
    used = next((r["_usage"] for r in rows if "_usage" in r), None)
    if used is not None:
        first = datetime.strptime(rows[0]["recorded_at"], "%Y-%m-%dT%H:%M:%S.%fZ").replace(tzinfo=timezone.utc)
        resets = int((first + timedelta(hours=2, minutes=40)).timestamp())
        lines.append(json.dumps({"timestamp": rows[0]["recorded_at"], "type": "event_msg", "payload": {
            "type": "token_count",
            "info": {"last_token_usage": {"total_tokens": 98000}, "model_context_window": 258400},
            "rate_limits": {"primary": {"used_percent": used, "window_minutes": 300, "resets_at": resets},
                            "secondary": {"used_percent": 42.0, "window_minutes": 10080,
                                          "resets_at": resets + 400000},
                            "rate_limit_reached_type": None}}}))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def cli_args(agent: str, data: dict) -> list[str] | None:
    """The agent-autosave command a recorded Bash call ran, if any."""
    command = ((data.get("tool_input") or {}).get("command") or "") if data.get("tool_name") == "Bash" else ""
    words = shlex.split(command) if "agent-autosave " in command else []
    return words[1:] if words and words[0].endswith("agent-autosave") else None


# The variable each agent sets in its shell tool (agent_autosave/origin.py),
# so a note the agent runs is credited to it, as in a real session.
TOOL_MARKERS = {"claude-code": "CLAUDE_CODE_CHILD_SESSION", "codex": "CODEX_TOOL_CALL_ID"}


def as_agent(agent: str, project: Path, args: list) -> None:
    """Run our CLI in the project from the agent's shell tool."""
    from agent_autosave import cli
    cwd, marker = os.getcwd(), TOOL_MARKERS[agent]
    os.chdir(project)
    os.environ[marker] = "1"
    try:
        cli.main(args)
    finally:
        del os.environ[marker]
        os.chdir(cwd)


def stamp(ts: datetime) -> str:
    return ts.strftime("%Y-%m-%dT%H:%M:%S.%fZ")


def build(name: str, parts: tuple[tuple[str, Path, str], ...]) -> None:
    from agent_autosave.compiler import compile_events, serialize
    from agent_autosave.render import render

    with tempfile.TemporaryDirectory() as tmp:
        scratch = Path(tmp).resolve()
        project = scratch / "hello"
        project.mkdir()
        os.environ["HOME"] = str(scratch / "home")
        os.environ["CODEX_HOME"] = str(scratch / "home/.codex")
        subprocess.run(["git", "init", "-q", "-b", "main", str(project)], check=True)
        install(project, agents=("claude-code", "codex"), command="agent-autosave")
        ledger = project / ".autosave/events.jsonl"
        asked = None
        times: list[datetime] = []  # the recorded time of the hook behind each ledger line
        pickup = 0  # ledger lines before the second agent's session
        shift = timedelta(0)
        for index, (agent, folder, session_id, *edit) in enumerate(parts):
            rows = session(folder, session_id)
            for change in edit:
                rows = change(rows)
            first = datetime.strptime(rows[0]["recorded_at"], "%Y-%m-%dT%H:%M:%S.%fZ")
            if index:  # the second agent starts three minutes after the first one quit
                shift = times[-1] + timedelta(minutes=3) - first
                pickup = len(times)
            rollout = codex_rollout(scratch / "rollout-{}.jsonl".format(index), rows)
            for row in rows:
                when = datetime.strptime(row["recorded_at"], "%Y-%m-%dT%H:%M:%S.%fZ") + shift
                data = localize(agent, row, project, rollout)
                args = cli_args(agent, data)
                if args:  # the agent ran our CLI here: run it too, as it did
                    as_agent(agent, project, args)
                if row.get("_statusline"):
                    statusline_reading(project, data, row["_statusline"])
                out = capture.handle(agent, data["hook_event_name"], json.dumps(data).encode(),
                                     env={"AGENT_AUTOSAVE_SESSION_END": "sync"})
                if row.get("_ask"):  # the low-battery ask the agent was given
                    asked = json.loads(out)["hookSpecificOutput"]["additionalContext"]
                if row.get("_then"):  # the agent then ran our CLI, as asked
                    as_agent(agent, project, row["_then"] + ["--quiet"])
                count = len(ledger.read_text(encoding="utf-8").splitlines()) if ledger.exists() else 0
                times += [when] * (count - len(times))
        if (project / ".autosave/errors.log").exists():
            raise SystemExit((project / ".autosave/errors.log").read_text())
        text = ledger.read_text(encoding="utf-8")
        for real in (str(project), str(scratch)):
            text = text.replace(real, PROJECT)
    events = [json.loads(line) for line in text.splitlines()]
    task_id = "t_" + times[0].strftime("%Y%m%d_%H%M%S%f")
    seen: dict[datetime, int] = {}
    for event in events[pickup:]:
        # The recorded reply describes that agent's own earlier run, not this
        # handoff, so the pick-up session keeps its hooks but not its reply.
        if event["kind"] == "turn_end":
            event.pop("last_message", None)
    for event, when in zip(events, times):
        seen[when] = seen.get(when, -1) + 1  # several events from one hook keep their order
        event["ts"] = stamp(when + timedelta(microseconds=seen[when]))
        event["task_id"] = task_id
        if event.get("transcript"):  # the agent's own log: a neutral path in the agent's layout
            event["transcript"] = TRANSCRIPTS[event["agent"]].format(event["session"])
    folder = ROOT / "examples" / name
    target = folder / ".autosave"
    target.mkdir(parents=True, exist_ok=True)
    (target / "events.jsonl").write_text("".join(json.dumps(e, sort_keys=True, separators=(",", ":")) + "\n"
                                                 for e in events), encoding="utf-8")
    save = compile_events(events, started=events[0]["ts"], task_id=task_id)
    (target / "save.json").write_bytes(serialize(save))
    (target / "SAVE.md").write_bytes(render(save).encode("utf-8"))
    sys.path.insert(0, str(ROOT / "examples"))
    from _replay import pickup_index, rebuild
    assert pickup_index(events) == pickup
    for path, data in rebuild(folder, name in GO_EXAMPLES).items():
        (folder / path).parent.mkdir(parents=True, exist_ok=True)
        (folder / path).write_bytes(data)
    if asked is not None:
        (folder / "ask.txt").write_text(asked.rstrip("\n") + "\n", encoding="utf-8")
    readme = folder / "README.md"
    readme.write_text(readme_text(readme.read_text(encoding="utf-8"), folder), encoding="utf-8")
    print("{}: {} events".format(name, len(events)))


def readme_text(current: str, folder: Path) -> str:
    """README.md: the hand-written story, then the generated before/after views."""
    story = current.split(README_START)[0].rstrip("\n")

    def fenced(path: str) -> str:
        text = (folder / path).read_text(encoding="utf-8").rstrip("\n")
        return "````markdown\n" + text + "\n````" if path.endswith(".md") else "````text\n" + text + "\n````"
    return "\n".join([story, "", README_START, "",
                      "## SAVE.md when the first agent stopped", "",
                      "[`before/SAVE.md`](before/SAVE.md), compiled from the ledger up to the second agent's first "
                      "event:", "", fenced("before/SAVE.md"), "",
                      "## What the next agent saw", "",
                      "[`context.txt`](context.txt): the block its SessionStart hook added to the session:", "",
                      fenced("context.txt"), "",
                      *go_section(folder),
                      "## SAVE.md after the handoff", "",
                      "[`.autosave/SAVE.md`](.autosave/SAVE.md), the save at the end of the second session:", "",
                      fenced(".autosave/SAVE.md"), "",
                      "## Replay it", "",
                      "```sh", "python replay.py          # rebuild the save from .autosave/events.jsonl",
                      "python replay.py --check  # exit 1 if a committed file differs from the replay", "```", ""])


def go_section(folder: Path) -> list:
    """For an example run under `go`: what it printed and Codex's first prompt."""
    if not (folder / "go.txt").exists():
        return []
    text = (folder / "go.txt").read_text(encoding="utf-8").rstrip("\n")
    return ["## What go showed, and the next agent's first prompt", "",
            "[`go.txt`](go.txt): the switch prompt (a terminal also shows the local time of the limit), then "
            "the resume block `go` started the next agent with:", "", "````text\n" + text + "\n````", ""]


MEMORY_NOTE = "hello.py prints with print(), not logging, so a check can read its stdout"
MEMORY_README = "<!-- generated by scripts/build-examples.py: do not edit below -->"


def build_memory_recall() -> None:
    """examples/memory-recall: Codex's session from codex-to-claude, plus the
    decision note Codex records before its last Stop and the user's `done`.
    Neither is in the recording; both are added here, with times between
    the recorded ones. replay.py derives everything else."""
    source = ROOT / "examples/codex-to-claude/.autosave/events.jsonl"
    events = [json.loads(line) for line in source.read_text(encoding="utf-8").splitlines()]
    events = events[:next(i for i, e in enumerate(events) if e["agent"] == "claude-code")]
    task_id = events[0]["task_id"]
    last_stop = max(i for i, e in enumerate(events) if e["kind"] == "turn_end")
    note = {"v": 1, "ts": "2026-10-15T13:48:30.000000Z", "agent": "cli", "session": "cli", "turn": 0,
            "kind": "note", "text": MEMORY_NOTE, "type": "decision", "by": "codex", "task_id": task_id}
    done = {"v": 1, "ts": "2026-10-15T13:51:10.000000Z", "agent": "cli", "session": "cli", "turn": 0,
            "kind": "task_done", "task_id": task_id}
    events = events[:last_stop] + [note] + events[last_stop:] + [done]
    folder = ROOT / "examples/memory-recall"
    (folder / ".autosave").mkdir(parents=True, exist_ok=True)
    (folder / ".autosave/events.jsonl").write_text(
        "".join(json.dumps(e, sort_keys=True, separators=(",", ":")) + "\n" for e in events), encoding="utf-8")
    subprocess.run([sys.executable, "replay.py"], cwd=str(folder), check=True, stdout=subprocess.DEVNULL)
    readme = folder / "README.md"
    readme.write_text(memory_readme_text(readme.read_text(encoding="utf-8"), folder), encoding="utf-8")
    print("memory-recall: {} events".format(len(events)))


def memory_readme_text(current: str, folder: Path) -> str:
    """README.md of memory-recall: the story, then the replayed files."""
    story = current.split(MEMORY_README)[0].rstrip("\n")
    page = next((folder / ".autosave/journal").rglob("*.md")).relative_to(folder).as_posix()

    def fenced(path: str) -> str:
        text = (folder / path).read_text(encoding="utf-8").rstrip("\n")
        return ("````markdown\n" if path.endswith(".md") else "````text\n") + text + "\n````"
    return "\n".join([story, "", MEMORY_README, "",
                      "## MEMORY.md after the review", "", "[`.autosave/MEMORY.md`](.autosave/MEMORY.md):", "",
                      fenced(".autosave/MEMORY.md"), "",
                      "## The journal page", "", "[`{0}`]({0}):".format(page), "", fenced(page), "",
                      "## What Claude Code starts with", "", "[`start.txt`](start.txt):", "", fenced("start.txt"), "",
                      "## What its prompt is given", "", "[`prompt.txt`](prompt.txt): " +
                      (folder / "prompt.txt").read_text(encoding="utf-8").strip(), "",
                      "[`recall.txt`](recall.txt):", "", fenced("recall.txt"), "",
                      "## Replay it", "",
                      "```sh", "python replay.py          # rebuild everything from .autosave/events.jsonl",
                      "python replay.py --check  # exit 1 if a committed file differs from the replay", "```", ""])


def main() -> None:
    background.spawn = lambda project: None  # rebuild in the hook itself
    # Git and --version calls wait instead of timing out, so a loaded machine
    # never changes the generated files (agent_autosave/timeouts.py). Every
    # hook and CLI call here runs in this process.
    timeouts.LENIENT = True
    for name, parts in EXAMPLES.items():
        build(name, parts)
    build_memory_recall()


if __name__ == "__main__":
    main()
